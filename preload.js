const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (ch) => (fn) => ipcRenderer.on(ch, (_e, ...a) => fn(...a));

contextBridge.exposeInMainWorld('sb', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  saveConfig: (cfg) => ipcRenderer.send('config:save', cfg),
  env: () => ipcRenderer.invoke('env'),
  registerHooks: () => ipcRenderer.invoke('hooks:register'),
  hello: () => ipcRenderer.invoke('daemon:hello'),
  uuid: () => ipcRenderer.invoke('uuid'),

  spawn: (opts) => ipcRenderer.invoke('pty:spawn', opts),
  snapshot: (id) => ipcRenderer.invoke('pty:snapshot', id),
  cwd: (id) => ipcRenderer.invoke('pty:cwd', id),
  write: (id, d) => ipcRenderer.send('pty:write', id, d),
  mirror: (id, d) => ipcRenderer.send('pty:mirror', id, d),
  resize: (id, c, r) => ipcRenderer.send('pty:resize', id, c, r),
  kill: (id) => ipcRenderer.send('pty:kill', id),
  quitAll: () => ipcRenderer.invoke('quit-all'),

  claudeStates: () => ipcRenderer.invoke('claude:states'),
  takeImport: () => ipcRenderer.invoke('import:take'),
  pidAlive: (pids) => ipcRenderer.invoke('pid-alive', pids),
  onImportReady: on('import:ready'),
  git: (paths) => ipcRenderer.invoke('git', paths),
  changes: (paths) => ipcRenderer.invoke('git:changes', paths),
  diff: (p) => ipcRenderer.invoke('git:diff', p),
  pickFolder: () => ipcRenderer.invoke('dialog:folder'),
  pickFiles: () => ipcRenderer.invoke('dialog:files'),
  pickParent: (cur) => ipcRenderer.invoke('dialog:parent', cur),
  createProject: (o) => ipcRenderer.invoke('project:create', o),
  popup: (items) => ipcRenderer.invoke('menu:popup', items),
  reveal: (p) => ipcRenderer.send('reveal', p),
  openEditor: (p) => ipcRenderer.send('open-editor', p),
  openExternal: (u) => ipcRenderer.send('open-external', u),
  badge: (n) => ipcRenderer.send('badge', n),
  notify: (o) => ipcRenderer.send('notify', o),
  pathForFile: (f) => webUtils.getPathForFile(f),
  clipboardImage: () => ipcRenderer.invoke('clipboard:image'),
  clipboardHasImage: () => ipcRenderer.invoke('clipboard:hasImage'),
  face: {
    state: () => ipcRenderer.invoke('face:state'),
    up: () => ipcRenderer.invoke('face:up'),
    down: () => ipcRenderer.invoke('face:down'),
    enroll: (img) => ipcRenderer.invoke('face:enroll', img),
    verify: (img) => ipcRenderer.invoke('face:verify', img),
    learn: (img) => ipcRenderer.invoke('face:learn', img),
    warm: () => ipcRenderer.invoke('face:warm'),
    remember: (img) => ipcRenderer.invoke('face:remember', img),
    reset: () => ipcRenderer.invoke('face:reset'),
  },
  touchId: () => ipcRenderer.invoke('touchid'),
  cameraAccess: () => ipcRenderer.invoke('camera:access'),
  onLock: on('portal:lock'),
  onWake: on('portal:wake'),

  onData: on('pty:data'),
  onExit: on('pty:exit'),
  onProcs: on('pty:procs'),
  procsNow: () => ipcRenderer.send('pty:procs-now'),
  onClaude: on('claude:event'),
  onMenu: on('menu'),
  onFocusPane: on('focus-pane'),
  onWindowFocus: on('window:focus'),
  onReconnected: on('daemon:reconnected'),
});
